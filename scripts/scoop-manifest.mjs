#!/usr/bin/env node
// Renders the Scoop manifest for nexdrew/scoop-bucket from a GitHub release.
//
//   gh api repos/nexdrew/blitzy-cli/releases/latest | node scripts/scoop-manifest.mjs
//   gh api repos/nexdrew/blitzy-cli/releases/tags/v1.3.0 | node scripts/scoop-manifest.mjs
//
// Reads the release JSON on stdin, extracts the tag and the sha256 digests that
// GitHub records for each uploaded asset, and prints the manifest to stdout. The
// release workflow pipes this into bucket/blitzy-cli.json in the bucket repo; the
// manifest is fully generated — never edit it by hand.

import { readFileSync } from 'node:fs'

const release = JSON.parse(readFileSync(0, 'utf8'))

const tag = release.tag_name
if (!/^v\d+\.\d+\.\d+$/.test(tag || '')) {
  console.error(`Unexpected tag_name: ${tag}`)
  process.exit(1)
}
const version = tag.slice(1)

// Scoop architectures -> release asset names (Scoop only ships the Windows exes).
const ASSETS = {
  '64bit': 'blitzy-windows-x64.exe',
  arm64: 'blitzy-windows-arm64.exe'
}

function sha256 (assetName) {
  const asset = (release.assets || []).find((a) => a.name === assetName)
  const digest = asset && asset.digest
  if (!digest || !digest.startsWith('sha256:')) {
    console.error(`Release ${tag} is missing a sha256 digest for asset ${assetName}`)
    process.exit(1)
  }
  return digest.slice('sha256:'.length)
}

const url = (assetName) =>
  `https://github.com/nexdrew/blitzy-cli/releases/download/${tag}/${assetName}`

// Scoop keeps the downloaded exe byte-identical (the `bin` pair only names the
// shim `blitzy`), so `gh attestation verify` works on the installed file.
const arch = (assetName) => ({
  url: url(assetName),
  hash: sha256(assetName),
  bin: [[assetName, 'blitzy']]
})

const manifest = {
  '##': 'GENERATED by scripts/scoop-manifest.mjs in nexdrew/blitzy-cli — do not edit by hand; the blitzy-cli release workflow regenerates this on every release.',
  version,
  description: 'Unofficial CLI for the Blitzy platform API',
  homepage: 'https://github.com/nexdrew/blitzy-cli',
  license: 'MIT',
  architecture: {
    '64bit': arch(ASSETS['64bit']),
    arm64: arch(ASSETS.arm64)
  },
  checkver: 'github',
  autoupdate: {
    architecture: {
      '64bit': { url: `https://github.com/nexdrew/blitzy-cli/releases/download/v$version/${ASSETS['64bit']}` },
      arm64: { url: `https://github.com/nexdrew/blitzy-cli/releases/download/v$version/${ASSETS.arm64}` }
    }
  }
}

console.log(JSON.stringify(manifest, null, 2))
